void apply_language(void) {
    guint i;

    i18n_ensure();
    for (i = 0; i < i18n_binds->len; i++)
        i18n_apply_one(&g_array_index(i18n_binds, I18nBind, i));
    refresh_welcome_heading();
    refresh_stats_ui();
    net_lessons_apply_lang();
    hw_lessons_apply_lang();
}
