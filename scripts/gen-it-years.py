def c(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def S(kicker, title, tip, *lines):
    return (kicker, title, tip, lines)


def Q(prompt, options, correct, hint):
    if len(options) != 4:
        raise SystemExit(f"need 4 options: {prompt}")
    if not 0 <= correct < 4:
        raise SystemExit(prompt)
    return (prompt, options, correct, hint)


def L(title, title_en, sub, sub_en, slides, quiz):
    if len(slides) != 3 or len(quiz) != 4:
        raise SystemExit(title)
    return {
        "title": title, "title_en": title_en,
        "sub": sub, "sub_en": sub_en,
        "slides": slides, "quiz": quiz,
    }


